  static List<BankInfo> getAllBanks() {
    return _banks;
  }

  static List<BankInfo> getIndianBanks() {
    return _banks.where((bank) => bank.country == 'India').toList();
  }

  static List<BankInfo> getGlobalBanks() {
    return _banks.where((bank) => bank.type == 'global').toList();
  }

  static List<BankInfo> getBanksByType(String type) {
    if (type.toLowerCase() == 'all') return _banks;
    return _banks.where((bank) => bank.type.toLowerCase() == type.toLowerCase()).toList();
  }

  static List<BankInfo> getTopBanksByRate(String duration, {int limit = 10}) {
    final sortedBanks = List<BankInfo>.from(_banks)
      ..sort((a, b) {
        final rateA = a.fdRates[duration] ?? 0.0;
        final rateB = b.fdRates[duration] ?? 0.0;
        return rateB.compareTo(rateA);
      });
    return sortedBanks.take(limit).toList();
  }

  static BankInfo? getBankByName(String name) {
    try {
      return _banks.firstWhere((bank) => bank.name.toLowerCase() == name.toLowerCase());
    } catch (e) {
      return null;
    }
  }
  
  // API Integrated Methods
  static String lastUpdated = 'Not synced';
  static bool isLive = false;

  static Future<List<BankInfo>> fetchAllBanks() async {
    try {
      final response = await BankRateApiService.fetchRates();
      lastUpdated = response.lastUpdated;
      isLive = false; // Data from API is unverified — never claim "Live"
      return response.banks;
    } catch (e) {
      isLive = false;
      return getAllBanks();
    }
  }

  static Future<List<BankInfo>> fetchTopBanks(String duration, {int limit = 10}) async {
    try {
      return await BankRateApiService.fetchTopBanks(duration, limit: limit);
    } catch (e) {
      return getTopBanksByRate(duration, limit: limit);
    }
  }

  static Future<List<BankInfo>> fetchIndianBanks() async {
    try {
      final response = await BankRateApiService.fetchRates();
      return response.banks.where((bank) => bank.country == 'India').toList();
    } catch (e) {
      return getIndianBanks();
    }
  }

  static Future<List<BankInfo>> fetchBanksByType(String type) async {
    try {
      final response = await BankRateApiService.fetchRates();
      if (type.toLowerCase() == 'all') return response.banks;
      return response.banks.where((bank) => bank.type.toLowerCase() == type.toLowerCase()).toList();
    } catch (e) {
      return getBanksByType(type);
    }
  }
