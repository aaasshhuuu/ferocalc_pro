import 'dart:io';
import 'dart:typed_data';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

class PdfGenerator {
  /// Sanitizes text for PDF generation by converting symbols like ₹ to Rs.
  /// because standard PostScript fonts (Helvetica) lack Unicode currency glyphs.
  static String sanitizeForPdf(String text) {
    return text.replaceAll('₹', 'Rs. ');
  }

  /// Generates the raw PDF bytes in memory.
  static Future<Uint8List> generatePdfBytes({
    required String title,
    required Map<String, String> inputs,
    required Map<String, String> results,
  }) async {
    final pdf = pw.Document();

    final cleanTitle = sanitizeForPdf(title);
    final cleanInputs = inputs.map((k, v) => MapEntry(sanitizeForPdf(k), sanitizeForPdf(v)));
    final cleanResults = results.map((k, v) => MapEntry(sanitizeForPdf(k), sanitizeForPdf(v)));

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (pw.Context context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(bottom: 16),
          child: pw.Text(
            'FeroCalc Financial Report',
            style: const pw.TextStyle(color: PdfColors.grey600, fontSize: 10),
          ),
        ),
        footer: (pw.Context context) => pw.Container(
          alignment: pw.Alignment.center,
          margin: const pw.EdgeInsets.only(top: 16),
          child: pw.Column(
            children: [
              pw.Divider(thickness: 0.5, color: PdfColors.grey400),
              pw.SizedBox(height: 4),
              pw.Text(
                'Generated by FeroCalc  *  Disclaimer: Results are for informational purposes only. Not financial advice.',
                style: const pw.TextStyle(color: PdfColors.grey500, fontSize: 9),
              ),
              pw.SizedBox(height: 2),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(color: PdfColors.grey400, fontSize: 8),
              ),
            ],
          ),
        ),
        build: (pw.Context context) {
          return [
            pw.Header(
              level: 0,
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    cleanTitle,
                    style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800),
                  ),
                  pw.Text(
                    'FeroCalc',
                    style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColors.amber800),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              'Date: ${DateTime.now().toLocal().toString().split(' ')[0]}',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
            pw.Divider(thickness: 1, color: PdfColors.grey300),
            pw.SizedBox(height: 12),

            pw.Text(
              'Inputs',
              style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey700),
            ),
            pw.SizedBox(height: 8),
            _buildTable(cleanInputs),

            pw.SizedBox(height: 16),
            pw.Text(
              'Results',
              style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey700),
            ),
            pw.SizedBox(height: 8),
            _buildTable(cleanResults),
          ];
        },
      ),
    );

    return pdf.save();
  }

  /// Generates the PDF report file and saves it in [outputDir] (or temporary directory).
  static Future<File> generateReport({
    required String title,
    required Map<String, String> inputs,
    required Map<String, String> results,
    Directory? outputDir,
  }) async {
    final bytes = await generatePdfBytes(
      title: title,
      inputs: inputs,
      results: results,
    );

    final Directory dir = outputDir ?? await getTemporaryDirectory();
    final safeTitle = title.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
    final file = File('${dir.path}/FeroCalc_${safeTitle}_${DateTime.now().millisecondsSinceEpoch}.pdf');
    await file.writeAsBytes(bytes);
    return file;
  }

  /// Generates the raw PDF bytes for a detailed schedule in memory.
  static Future<Uint8List> generateSchedulePdfBytes({
    required String title,
    String subtitle = '',
    String? scheduleSectionTitle,
    required Map<String, String> inputs,
    required Map<String, String> summary,
    required List<String> tableHeaders,
    required List<List<String>> tableRows,
    String? disclaimer,
    Map<int, pw.Alignment>? columnAlignments,
  }) async {
    final pdf = pw.Document();

    final cleanTitle = sanitizeForPdf(title);
    final cleanSubtitle = sanitizeForPdf(subtitle);
    final effectiveSectionTitle = scheduleSectionTitle ??
        (title.contains('SSY') || title.contains('Sukanya')
            ? 'Year-wise Schedule'
            : 'Repayment Schedule');
    final cleanScheduleSectionTitle = sanitizeForPdf(effectiveSectionTitle);
    final cleanInputs = inputs.map((k, v) => MapEntry(sanitizeForPdf(k), sanitizeForPdf(v)));
    final cleanSummary = summary.map((k, v) => MapEntry(sanitizeForPdf(k), sanitizeForPdf(v)));
    final cleanHeaders = tableHeaders.map(sanitizeForPdf).toList();
    final cleanRows = tableRows
        .map((row) => row.map(sanitizeForPdf).toList())
        .toList();
    final cleanDisclaimer = disclaimer != null ? sanitizeForPdf(disclaimer) : '';

    final effectiveAlignments = columnAlignments ?? {
      for (int i = 0; i < cleanHeaders.length; i++)
        i: (cleanHeaders[i].toLowerCase() == 'age' || i == 0)
            ? pw.Alignment.center
            : pw.Alignment.centerRight,
    };

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (pw.Context context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(bottom: 16),
          child: pw.Text(
            'FeroCalc Financial Report',
            style: const pw.TextStyle(color: PdfColors.grey600, fontSize: 10),
          ),
        ),
        footer: (pw.Context context) => pw.Container(
          alignment: pw.Alignment.center,
          margin: const pw.EdgeInsets.only(top: 16),
          child: pw.Column(
            children: [
              pw.Divider(thickness: 0.5, color: PdfColors.grey400),
              pw.SizedBox(height: 4),
              pw.Text(
                'Generated by FeroCalc  *  Disclaimer: Results are for informational purposes only. Not financial advice.',
                style: const pw.TextStyle(color: PdfColors.grey500, fontSize: 9),
              ),
              pw.SizedBox(height: 2),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(color: PdfColors.grey400, fontSize: 8),
              ),
            ],
          ),
        ),
        build: (pw.Context context) {
          return [
            pw.Header(
              level: 0,
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Expanded(
                    child: pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text(
                          cleanTitle,
                          style: pw.TextStyle(
                            fontSize: 20,
                            fontWeight: pw.FontWeight.bold,
                            color: PdfColors.blueGrey800,
                          ),
                        ),
                        if (cleanSubtitle.isNotEmpty) ...[
                          pw.SizedBox(height: 2),
                          pw.Text(
                            cleanSubtitle,
                            style: const pw.TextStyle(
                              fontSize: 11,
                              color: PdfColors.blueGrey600,
                            ),
                          ),
                        ],
                      ],
                    ),
                  ),
                  pw.Text(
                    'FeroCalc',
                    style: pw.TextStyle(
                      fontSize: 16,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.amber800,
                    ),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              'Date: ${DateTime.now().toLocal().toString().split(' ')[0]}',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
            pw.Divider(thickness: 1, color: PdfColors.grey300),
            pw.SizedBox(height: 10),

            if (cleanInputs.isNotEmpty) ...[
              pw.Text(
                'Inputs',
                style: pw.TextStyle(
                  fontSize: 13,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blueGrey700,
                ),
              ),
              pw.SizedBox(height: 6),
              _buildTable(cleanInputs),
              pw.SizedBox(height: 12),
            ],

            if (cleanSummary.isNotEmpty) ...[
              pw.Text(
                'Summary',
                style: pw.TextStyle(
                  fontSize: 13,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blueGrey700,
                ),
              ),
              pw.SizedBox(height: 6),
              _buildTable(cleanSummary),
              pw.SizedBox(height: 14),
            ],

            if (cleanScheduleSectionTitle.isNotEmpty) ...[
              pw.Text(
                cleanScheduleSectionTitle,
                style: pw.TextStyle(
                  fontSize: 13,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blueGrey700,
                ),
              ),
              pw.SizedBox(height: 6),
            ],
            pw.TableHelper.fromTextArray(
              context: context,
              headers: cleanHeaders,
              data: cleanRows,
              headerStyle: pw.TextStyle(
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
                fontSize: 8.5,
              ),
              headerDecoration:
                  const pw.BoxDecoration(color: PdfColors.blueGrey700),
              headerAlignment: pw.Alignment.center,
              headerAlignments: effectiveAlignments,
              cellStyle: const pw.TextStyle(fontSize: 8),
              cellHeight: 20,
              cellPadding:
                  const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
              cellAlignments: effectiveAlignments,
            ),
            if (cleanDisclaimer.isNotEmpty) ...[
              pw.SizedBox(height: 12),
              pw.Container(
                padding: const pw.EdgeInsets.all(8),
                decoration: pw.BoxDecoration(
                  color: PdfColors.amber50,
                  borderRadius: pw.BorderRadius.circular(4),
                  border: pw.Border.all(color: PdfColors.amber200),
                ),
                child: pw.Text(
                  cleanDisclaimer,
                  style: const pw.TextStyle(fontSize: 8, color: PdfColors.amber900),
                ),
              ),
            ],
          ];
        },
      ),
    );

    return pdf.save();
  }

  /// Generates the schedule PDF report file and saves it in [outputDir] (or temporary directory).
  static Future<File> generateScheduleReport({
    required String title,
    String subtitle = '',
    String? scheduleSectionTitle,
    required Map<String, String> inputs,
    required Map<String, String> summary,
    required List<String> tableHeaders,
    required List<List<String>> tableRows,
    String? disclaimer,
    Map<int, pw.Alignment>? columnAlignments,
    Directory? outputDir,
  }) async {
    final bytes = await generateSchedulePdfBytes(
      title: title,
      subtitle: subtitle,
      scheduleSectionTitle: scheduleSectionTitle,
      inputs: inputs,
      summary: summary,
      tableHeaders: tableHeaders,
      tableRows: tableRows,
      disclaimer: disclaimer,
      columnAlignments: columnAlignments,
    );

    final Directory dir = outputDir ?? await getTemporaryDirectory();
    final safeTitle = title.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
    final file = File(
      '${dir.path}/FeroCalc_${safeTitle}_Schedule_${DateTime.now().millisecondsSinceEpoch}.pdf',
    );
    await file.writeAsBytes(bytes);
    return file;
  }

  static pw.Widget _buildTable(Map<String, String> data) {
    return pw.TableHelper.fromTextArray(
      context: null,
      data: <List<String>>[
        <String>['Parameter', 'Value'],
        ...data.entries.map((e) => [e.key, e.value]),
      ],
      headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey700),
      cellHeight: 26,
      cellAlignments: {
        0: pw.Alignment.centerLeft,
        1: pw.Alignment.centerRight,
      },
    );
  }
}
